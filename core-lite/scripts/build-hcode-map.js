#!/usr/bin/env node
/**
 * build-hcode-map.js — one-time, offline generator (dev only, no prod deps).
 *
 * Turns the MOPH hospital export into a hcode5 → { province, region, hospital }
 * lookup used by the dashboard for "แบ่งตามเขตสุขภาพและจังหวัด" (TOR 4.12.x.2).
 *
 * Why a generator instead of a hand-written table:
 *   The export has ~900 rows and there is NO arithmetic rule from hcode → province,
 *   so the map must come from the source data. Transcribing by hand would risk
 *   silent errors on a production healthcare dashboard, so we parse the file.
 *
 * Input:  a TAB-separated export of the sheet (columns: <blank> เขต จังหวัด รหัสรพ โรงพยาบาล ...).
 *         Save the provided .xlsx as .tsv (Excel: Save As → "Text (Tab delimited)")
 *         or .csv (the script auto-detects tab vs comma).
 * Output: core-lite/src/data/hcode-to-area.js
 *
 * Usage:
 *   node scripts/build-hcode-map.js <path-to-export.tsv> [output.js]
 *
 * The script validates that each row's เขต matches the province→region map and
 * reports any mismatches instead of silently trusting the file.
 */

const fs = require('fs');
const path = require('path');
const { PROVINCE_TO_REGION, regionOf } = require('../src/data/health-regions');

function die(msg) { console.error('ERROR: ' + msg); process.exit(1); }

const inFile = process.argv[2];
if (!inFile) die('missing input file.\n  Usage: node scripts/build-hcode-map.js <export.tsv> [output.js]');
if (!fs.existsSync(inFile)) die('input file not found: ' + inFile);

const outFile = process.argv[3] || path.join(__dirname, '../src/data/hcode-to-area.js');

const raw = fs.readFileSync(inFile, 'utf8').replace(/^\uFEFF/, ''); // strip BOM
const lines = raw.split(/\r?\n/).filter(l => l.trim() !== '');

// Auto-detect delimiter: tab if any line has tabs, else comma.
const delim = raw.includes('\t') ? '\t' : ',';

const map = {};
const mismatches = [];
let parsed = 0, skipped = 0;

for (const line of lines) {
  const cols = line.split(delim).map(c => c.trim().replace(/^"|"$/g, ''));
  // Find เขต / จังหวัด / รหัส columns. The export has a leading blank column,
  // so locate by content rather than fixed index to be robust.
  // Expected layout: ['', เขต, จังหวัด, รหัส, โรงพยาบาล, ...]
  let regionCol = -1;
  for (let i = 0; i < cols.length - 2; i++) {
    if (/^\d{1,2}$/.test(cols[i]) && cols[i + 1] && /^\d{4,5}$/.test(cols[i + 2] || '')) {
      regionCol = i; break;
    }
  }
  if (regionCol === -1) { skipped++; continue; } // header or non-data row

  const region   = parseInt(cols[regionCol], 10);
  const province = cols[regionCol + 1];
  const hcode    = cols[regionCol + 2];
  const hospital = cols[regionCol + 3] || '';

  if (!hcode || !province) { skipped++; continue; }

  // Cross-check against the province→region reference.
  const expected = regionOf(province);
  if (expected != null && expected !== region) {
    mismatches.push(`hcode ${hcode} (${province}): sheet=เขต${region} ref=เขต${expected}`);
  }

  map[hcode] = { province, region, hospital };
  parsed++;
}

const provinces = new Set(Object.values(map).map(v => v.province));
console.log(`Parsed ${parsed} rows, skipped ${skipped} (headers/blank).`);
console.log(`Distinct provinces: ${provinces.size}, distinct hcodes: ${Object.keys(map).length}`);

if (mismatches.length) {
  console.warn(`\nWARNING: ${mismatches.length} เขต mismatches vs reference map:`);
  mismatches.slice(0, 20).forEach(m => console.warn('  ' + m));
  if (mismatches.length > 20) console.warn(`  ...and ${mismatches.length - 20} more`);
}

const banner = `/**
 * hcode-to-area.js — AUTO-GENERATED by scripts/build-hcode-map.js. DO NOT EDIT BY HAND.
 * hcode5 → { province (จังหวัด), region (เขตสุขภาพ 1-13), hospital }
 * Rows: ${Object.keys(map).length}  Generated: ${new Date().toISOString()}
 */
`;
const body = 'const HCODE_TO_AREA = ' + JSON.stringify(map, null, 2) + ';\n\n'
  + 'module.exports = { HCODE_TO_AREA };\n';

fs.writeFileSync(outFile, banner + body, 'utf8');
console.log(`\nWrote ${outFile}`);
